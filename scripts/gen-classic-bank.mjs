// Builds public/classic-games/gold-rush-bank.js, the question bank for the classic Gold Rush game.
// Source: src/data/content/review.json when it exists (public review bank), otherwise word/definition
// questions made from glossary.json. NEVER reads questions.json (graded answer keys stay out of the site).
// Re-run after review.json lands:  node scripts/gen-classic-bank.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const root = new URL("..", import.meta.url);
const p = (f) => new URL(f, root);
const out = p("public/classic-games/gold-rush-bank.js");

// tiny deterministic RNG so the committed file is stable between runs
let seed = 20261114;
const rnd = (n) => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed % n; };
const pick = (arr, k, avoid) => {
  const pool = arr.filter((x) => !avoid.includes(x)); const res = [];
  while (res.length < k && pool.length) res.push(pool.splice(rnd(pool.length), 1)[0]);
  return res;
};
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const bank = {};
let source;
const reviewPath = p("src/data/content/review.json");
if (existsSync(reviewPath)) {
  source = "review.json";
  const review = JSON.parse(readFileSync(reviewPath, "utf8"));
  for (const [n, rows] of Object.entries(review)) {
    const ok = rows.filter((r) => r.q && r.a && Array.isArray(r.wrong) && r.wrong.filter(Boolean).length >= 3);
    if (ok.length) bank[n] = ok.map((r) => [0, r.q, r.a, r.wrong[0], r.wrong[1], r.wrong[2], r.why || ""]);
  }
} else {
  source = "glossary.json";
  const glossary = JSON.parse(readFileSync(p("src/data/content/glossary.json"), "utf8"));
  const byCh = {};
  for (const g of glossary) (byCh[g.chapter] ||= []).push(g);
  const all = glossary.map((g) => g.term);
  for (const [n, list] of Object.entries(byCh)) {
    const terms = list.map((g) => g.term);
    bank[n] = list.map((g) => {
      const esc = g.term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const def = g.definition.replace(new RegExp("\\b" + esc + "\\b", "gi"), "____").replace(/\.$/, "");
      let wrong = pick(terms, 3, [g.term]);
      if (wrong.length < 3) wrong = wrong.concat(pick(all, 3 - wrong.length, [g.term, ...wrong]));
      return [0, "Which term means: " + def + "?", g.term, ...wrong, cap(g.term) + ": " + g.definition];
    });
  }
}

const body = "// GENERATED by scripts/gen-classic-bank.mjs from src/data/content/" + source + ". Do not edit by hand.\n" +
  "// Each row: [lesson, question, correct answer, wrong, wrong, wrong, why]\n" +
  "window.BEDROCK_BANK_SOURCE = " + JSON.stringify(source) + ";\n" +
  "window.BEDROCK_BANK = " + JSON.stringify(bank).replace(/\],\[/g, "],\n[") + ";\n";
writeFileSync(out, body);
console.log("gold-rush-bank.js:", source, Object.values(bank).reduce((s, r) => s + r.length, 0), "questions");
