// Prints the SQL that loads Classwork vocabulary (b_cw_terms) from the public glossary.
// Vocabulary and definitions are public (src/data/content/glossary.json), so this SQL is safe to commit.
// Usage: node scripts/classwork/terms-sql.mjs > /tmp/terms.sql   (then paste into the Supabase SQL Editor)
// Re-run it whenever the glossary changes: it replaces the whole word list. Saved stories keep their own
// copy of the words they used, so changing the list never breaks finished work.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, "src/data/content", f), "utf8"));
const glossary = read("glossary.json");
const chapters = read("chapters.json");

// chapter id ("12" or "12a") → database ref (12 or 1201) and realm, same rule as src/data/site.ts
const refOf = (id) => { const m = String(id).match(/^(\d+)([a-z]?)$/i); return m[2] ? +m[1] * 100 + (m[2].toLowerCase().charCodeAt(0) - 96) : +m[1]; };
const realmOf = new Map(chapters.map((c) => [String(c.id ?? c.n).toLowerCase(), c.realm]));

// Words that can't carry a real-life story: people's names, and everyday words whose science meaning is easy to
// "use" by accident (a spring in March, a minute of time). They stay in Learn, Practice and tests.
// The list lives in src/data/classwork-story-skip.json and is shared with the Classwork page.
const NOT_FOR_STORIES = new Set(JSON.parse(fs.readFileSync(path.join(root, "src/data/classwork-story-skip.json"), "utf8")));

const esc = (s) => String(s).replace(/'/g, "''");
const n = new Map();
const rows = [];
for (const g of glossary) {
  const id = String(g.chapter).toLowerCase();
  if (!realmOf.has(id)) { console.error(`skip "${g.term}": chapter ${g.chapter} is not in chapters.json`); continue; }
  const ref = refOf(id);
  const k = (n.get(ref) ?? 0) + 1; n.set(ref, k);
  const def = g.definition.charAt(0).toUpperCase() + g.definition.slice(1);
  rows.push(`(${ref}, ${realmOf.get(id)}, ${k}, '${esc(g.term)}', '${esc(def)}', ${!NOT_FOR_STORIES.has(g.term.toLowerCase())})`);
}
process.stdout.write(`-- Classwork vocabulary: ${rows.length} words from src/data/content/glossary.json (generated by scripts/classwork/terms-sql.mjs).
delete from public.b_cw_terms;
insert into public.b_cw_terms (ref, realm, n, term, def, story_ok) values
${rows.join(",\n")};
`);
